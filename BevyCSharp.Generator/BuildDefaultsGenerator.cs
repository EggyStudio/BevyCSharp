using System;
using Microsoft.CodeAnalysis;

namespace Bevy.Generator;

/// <summary>
/// Tells the engine a program's executable was built in Debug, so a game from the package watches
/// its assets in Debug and not in Release.
/// </summary>
/// <remarks>
/// <para>
/// The package's props make the build's <c>Configuration</c>, <c>OutputType</c> and
/// <c>IsTestProject</c> visible here. A project building an executable in Debug that is no test
/// project gets a module initializer calling <c>BuildDefaults.ProgramBuiltInDebug</c> with its own
/// assembly, which the CLR runs before the program's first line, and every other project gets
/// nothing, a library, a test project and a Release build among them. The default reaches the
/// program alone, since the engine passes over a call naming an assembly the process did not start
/// from.
/// </para>
/// <para>
/// A project that reads the generator without the package's props, as the engine's own programs
/// do, sees none of the three and gets nothing either, so they keep the default off.
/// </para>
/// </remarks>
[Generator(LanguageNames.CSharp)]
public sealed class BuildDefaultsGenerator : IIncrementalGenerator
{
    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var debugProgram = context.AnalyzerConfigOptionsProvider.Select(static (options, _) =>
        {
            var global = options.GlobalOptions;
            var debug = global.TryGetValue("build_property.Configuration", out var configuration)
                        && string.Equals(configuration, "Debug", StringComparison.OrdinalIgnoreCase);
            var program = global.TryGetValue("build_property.OutputType", out var output)
                          && (string.Equals(output, "Exe", StringComparison.OrdinalIgnoreCase)
                              || string.Equals(output, "WinExe", StringComparison.OrdinalIgnoreCase));
            var test = global.TryGetValue("build_property.IsTestProject", out var isTest)
                       && string.Equals(isTest, "true", StringComparison.OrdinalIgnoreCase);
            return debug && program && !test;
        });

        var hasEngine = context.CompilationProvider.Select(static (compilation, _) =>
            compilation.GetTypeByMetadataName("Bevy.BuildDefaults") is not null);

        context.RegisterSourceOutput(debugProgram.Combine(hasEngine), static (spc, pair) =>
        {
            if (pair.Left && pair.Right) spc.AddSource("BuildDefaults.g.cs", Source);
        });
    }

    private const string Source =
        "// <auto-generated by BevyCSharp.Generator />\n"
        + "#nullable enable\n\n"
        + "namespace Bevy.Generated;\n\n"
        + "/// <summary>Tells the engine this program was built in Debug.</summary>\n"
        + "internal static class BuildDefaultsRegistration\n"
        + "{\n"
        + "    /// <summary>Records the build before the program's first line, so its config watches its assets unless it says otherwise.</summary>\n"
        + "    [global::System.Runtime.CompilerServices.ModuleInitializer]\n"
        + "    internal static void Initialize()\n"
        + "        => global::Bevy.BuildDefaults.ProgramBuiltInDebug(typeof(BuildDefaultsRegistration).Assembly);\n"
        + "}\n";
}
