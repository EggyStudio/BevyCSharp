using System;
using Microsoft.CodeAnalysis;

namespace Bevy.Generator;

/// <summary>
/// Tells the engine a program's executable was built in Debug, so a game from the package watches
/// its assets in Debug and not in Release.
/// </summary>
/// <remarks>
/// <para>
/// The package's props make the build's <c>Configuration</c>, <c>OutputType</c>,
/// <c>IsTestProject</c> and <c>IsTestingPlatformApplication</c> visible here, with the project's
/// folder and its build folder. A project building an executable in Debug that is no test project
/// gets a module initializer calling <c>BuildDefaults.ProgramBuiltInDebug</c> with its own assembly
/// and the two folders, which the CLR runs before the program's first line, and every other project
/// gets nothing, a library, a test project and a Release build among them. A test project is told
/// by either property, since a test executable on Microsoft's Testing Platform without the test SDK
/// sets the second alone. The default reaches the program alone, since the engine passes over a
/// call naming an assembly the process did not start from.
/// </para>
/// <para>
/// A project that reads the generator without the package's props, as the engine's own programs
/// do, sees none of them and gets nothing either, so they keep the default off.
/// </para>
/// </remarks>
[Generator(LanguageNames.CSharp)]
public sealed class BuildDefaultsGenerator : IIncrementalGenerator
{
    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        // Whether the project is a program built in Debug, and its folders where it is, a tuple so
        // an unchanged build is cached as the same.
        var debugProgram = context.AnalyzerConfigOptionsProvider.Select(static (options, _) =>
        {
            var global = options.GlobalOptions;
            var debug = global.TryGetValue("build_property.Configuration", out var configuration)
                        && string.Equals(configuration, "Debug", StringComparison.OrdinalIgnoreCase);
            var program = global.TryGetValue("build_property.OutputType", out var output)
                          && (string.Equals(output, "Exe", StringComparison.OrdinalIgnoreCase)
                              || string.Equals(output, "WinExe", StringComparison.OrdinalIgnoreCase));
            var test = IsTrue(global, "build_property.IsTestProject") || IsTrue(global, "build_property.IsTestingPlatformApplication");
            if (!debug || !program || test) return (Given: false, Project: "", Intermediate: "");

            global.TryGetValue("build_property.MSBuildProjectDirectory", out var project);
            global.TryGetValue("build_property.BaseIntermediateOutputPath", out var intermediate);
            return (Given: true, Project: project ?? "", Intermediate: intermediate ?? "");
        });

        var hasEngine = context.CompilationProvider.Select(static (compilation, _) =>
            compilation.GetTypeByMetadataName("Bevy.BuildDefaults") is not null);

        context.RegisterSourceOutput(debugProgram.Combine(hasEngine), static (spc, pair) =>
        {
            if (pair.Left.Given && pair.Right) spc.AddSource("BuildDefaults.g.cs", Source(pair.Left.Project, pair.Left.Intermediate));
        });
    }

    private static bool IsTrue(Microsoft.CodeAnalysis.Diagnostics.AnalyzerConfigOptions options, string key) =>
        options.TryGetValue(key, out var value) && string.Equals(value, "true", StringComparison.OrdinalIgnoreCase);

    /// <summary>The initializer, handing over the project's folders where the build named them.</summary>
    private static string Source(string project, string intermediate)
    {
        var folders = project.Length == 0 ? "" : $", {Verbatim(project)}, {Verbatim(intermediate)}";
        return "// <auto-generated by BevyCSharp.Generator />\n"
            + "#nullable enable\n\n"
            + "namespace Bevy.Generated;\n\n"
            + "/// <summary>Tells the engine this program was built in Debug, and from which project.</summary>\n"
            + "internal static class BuildDefaultsRegistration\n"
            + "{\n"
            + "    /// <summary>Records the build before the program's first line, so its config watches its project's assets unless it says otherwise.</summary>\n"
            + "    [global::System.Runtime.CompilerServices.ModuleInitializer]\n"
            + "    internal static void Initialize()\n"
            + $"        => global::Bevy.BuildDefaults.ProgramBuiltInDebug(typeof(BuildDefaultsRegistration).Assembly{folders});\n"
            + "}\n";
    }

    /// <summary>A path as a verbatim string, its quotes doubled.</summary>
    private static string Verbatim(string text) => "@\"" + text.Replace("\"", "\"\"") + "\"";
}
